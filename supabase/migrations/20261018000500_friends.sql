-- User-level, two-way friendships. The legacy public.friend table is untouched.
create table public.friendship (
 id bigint generated by default as identity primary key,
 requester uuid not null references public.user_account(user_id) on delete cascade,
 addressee uuid not null references public.user_account(user_id) on delete cascade,
 status text not null check (status in ('pending', 'accepted')),
 created_at timestamptz not null default now(),
 responded_at timestamptz,
 check (requester <> addressee)
);
create unique index friendship_pair on public.friendship (least(requester, addressee), greatest(requester, addressee));
create index friendship_addressee on public.friendship(addressee);
alter table public.friendship enable row level security;
revoke all on public.friendship from public, anon, authenticated;
grant select on public.friendship to authenticated;
create policy "Participants can read friendships" on public.friendship for select to authenticated
 using ((select auth.uid()) in (requester, addressee));

alter table public.notification alter column tcg_account_id drop not null;
alter table public.notification add column friend_user uuid references public.user_account(user_id) on delete cascade;
alter table public.notification drop constraint notification_kind_check;
alter table public.notification add constraint notification_kind_check check
 (kind in ('offer_received','offer_accepted','offer_declined','offer_cancelled','partner_done','trade_match','friend_request','friend_accepted','friend_card'));
create index notification_friend_card_rate_limit on public.notification(tcg_account_id, friend_user, their_card_id, created_at desc) where kind = 'friend_card';

create function public.send_friend_request(p_username text) returns text
 language plpgsql security definer set search_path = '' as $$
declare me uuid := auth.uid(); other_user uuid; f public.friendship;
begin
 if me is null then raise exception 'Not authenticated' using errcode = '42501'; end if;
 select u.user_id into other_user from public.user_account u
 where u.username is not null and lower(u.username) = lower(p_username);
 if other_user is null then raise exception 'Player not found'; end if;
 if me = other_user then raise exception 'You cannot add yourself'; end if;
 -- Serialize even when the pair has no row yet; opposite requests lock in the same order.
 perform 1 from public.user_account u where u.user_id in (me, other_user) order by u.user_id for no key update;
 select * into f from public.friendship where least(requester,addressee) = least(me,other_user)
 and greatest(requester,addressee) = greatest(me,other_user) for update;
 if found then
  if f.status = 'accepted' then raise exception 'You are already friends'; end if;
  if f.requester = me then raise exception 'Friend request already sent'; end if;
  update public.friendship set status = 'accepted', responded_at = now() where id = f.id;
  insert into public.notification(user_id,kind,friend_user,partner_name)
   select other_user,'friend_accepted',me,coalesce(username,'') from public.user_account where user_id = me;
  return 'accepted';
 end if;
 insert into public.friendship(requester,addressee,status) values(me,other_user,'pending');
 insert into public.notification(user_id,kind,friend_user,partner_name)
  select other_user,'friend_request',me,coalesce(username,'') from public.user_account where user_id = me;
 return 'sent';
end $$;

create function public.respond_friend_request(p_request bigint, p_accept boolean) returns void
 language plpgsql security definer set search_path = '' as $$
declare me uuid := auth.uid(); f public.friendship;
begin
 if me is null then raise exception 'Not authenticated' using errcode = '42501'; end if;
 select * into f from public.friendship where id = p_request and addressee = me and status = 'pending' for update;
 if not found then raise exception 'Request not found'; end if;
 if p_accept then
  update public.friendship set status = 'accepted', responded_at = now() where id = f.id;
  insert into public.notification(user_id,kind,friend_user,partner_name)
   select f.requester,'friend_accepted',me,coalesce(username,'') from public.user_account where user_id = me;
 else
  delete from public.friendship where id = f.id;
 end if;
end $$;

create function public.remove_friend(p_user uuid) returns void
 language plpgsql security definer set search_path = '' as $$
declare me uuid := auth.uid();
begin
 if me is null then raise exception 'Not authenticated' using errcode = '42501'; end if;
 delete from public.friendship where (requester = me and addressee = p_user) or (requester = p_user and addressee = me);
 if not found then raise exception 'Request not found'; end if;
end $$;

create function public.list_friends() returns table(user_id uuid, username text, status text, request_id bigint, since timestamptz, pocket_accounts jsonb)
 language plpgsql stable security definer set search_path = '' as $$
begin
 if auth.uid() is null then raise exception 'Not authenticated' using errcode = '42501'; end if;
 return query select u.user_id,u.username::text,
 case when f.status = 'accepted' then 'friend' when f.requester = auth.uid() then 'outgoing' else 'incoming' end,
 f.id,coalesce(f.responded_at,f.created_at),
 case when f.status = 'accepted' then coalesce((select jsonb_agg(jsonb_build_object('tcg_account_id',a.tcg_account_id,'name',a.tcg_id_username,'tcg_id',a.tcg_id) order by a.tcg_account_id)
 from public.player_tcg_account a where a.user_id = u.user_id),'[]'::jsonb) else '[]'::jsonb end
 from public.friendship f join public.user_account u on u.user_id = case when f.requester = auth.uid() then f.addressee else f.requester end
 where auth.uid() in (f.requester,f.addressee) order by f.created_at,f.id;
end $$;

create function public.my_friend_account_ids() returns setof uuid
 language plpgsql stable security definer set search_path = '' as $$
begin
 if auth.uid() is null then raise exception 'Not authenticated' using errcode = '42501'; end if;
 return query select a.tcg_account_id from public.player_tcg_account a join public.friendship f
 on a.user_id = case when f.requester = auth.uid() then f.addressee else f.requester end
 where f.status = 'accepted' and auth.uid() in (f.requester,f.addressee);
end $$;

create function public.friend_cards(p_user uuid) returns table(tcg_account_id uuid, account_name text, list text, card_id uuid, card_name text, card_local_id text, set_name text, rarity_name text, card_image text, language text, quantity int, exclusive boolean)
 language plpgsql stable security definer set search_path = '' as $$
begin
 if auth.uid() is null then raise exception 'Not authenticated' using errcode = '42501'; end if;
 if not exists(select 1 from public.friendship f where f.status = 'accepted' and
 ((f.requester = auth.uid() and f.addressee = p_user) or (f.addressee = auth.uid() and f.requester = p_user))) then
 raise exception 'Not friends' using errcode = '42501'; end if;
 return query with entries as (
 select w.tcg_account_id,'wishlist'::text as list,w.card_id,w.language,w.quantity,false as exclusive from public.wishlist w
 union all
 select t.tcg_account_id,'trade',t.card_id,t.language,t.quantity,exists(select 1 from public.exclusive_trade e where e.trade_card_id = t.id) from public.cards_available_for_trade t
 ) select a.tcg_account_id,a.tcg_id_username,e.list,c.card_id,c.card_name,c.card_local_id,s.set_name::text,r.name::text,c.card_image,e.language,e.quantity,e.exclusive
 from entries e join public.player_tcg_account a on a.tcg_account_id = e.tcg_account_id
 join public.card c on c.card_id = e.card_id left join public.set s on s.set_id = c.set_id left join public.rarity r on r.rarity_id = c.rarity_id
 where a.user_id = p_user;
end $$;

create function public.market_card_counts_friends() returns table(card_id uuid, has_count integer, wants_count integer)
 language plpgsql stable security definer set search_path = '' as $$
begin
 if auth.uid() is null then raise exception 'Not authenticated' using errcode = '42501'; end if;
 return query with accounts as (select public.my_friend_account_ids() as id), entries as (
 select t.card_id,t.tcg_account_id,'has'::text as side from public.cards_available_for_trade t join accounts a on a.id = t.tcg_account_id
 union all select w.card_id,w.tcg_account_id,'wants' from public.wishlist w join accounts a on a.id = w.tcg_account_id
 ) select e.card_id,(count(distinct e.tcg_account_id) filter(where e.side = 'has'))::integer,
 (count(distinct e.tcg_account_id) filter(where e.side = 'wants'))::integer from entries e group by e.card_id;
end $$;

-- Preserve the existing reciprocal trade-match notifications.
create or replace function public.add_cards_to_tcg_account(p_tcg_account_id uuid, p_category text, p_cards jsonb)
  returns integer
  language plpgsql
  security definer
  set search_path = ''
  as $$
declare
  saved integer;
begin
  if not public.owns_tcg_account(p_tcg_account_id) then
    raise exception 'TCG account not found' using errcode = '42501';
  end if;
  if jsonb_typeof(p_cards) <> 'array' or jsonb_array_length(p_cards) = 0 then
    raise exception 'No cards to add' using errcode = '22023';
  end if;

  -- Serialize additions by this account before changing lists or checking the
  -- rate limit, including concurrent batches touching different cards.
  perform 1 from public.player_tcg_account
    where tcg_account_id = p_tcg_account_id for update;

  if p_category = 'wishlist' then
    insert into public.wishlist as w (tcg_account_id, card_id, language, quantity)
    select p_tcg_account_id, c.card_id, c.language, sum(c.quantity)
    from jsonb_to_recordset(p_cards) as c(card_id uuid, language text, quantity integer)
    group by c.card_id, c.language
    on conflict (tcg_account_id, card_id, language)
      do update set quantity = w.quantity + excluded.quantity, updated_at = now();
  elsif p_category = 'trade' then
    insert into public.cards_available_for_trade as t (tcg_account_id, card_id, language, quantity)
    select p_tcg_account_id, c.card_id, c.language, sum(c.quantity)
    from jsonb_to_recordset(p_cards) as c(card_id uuid, language text, quantity integer)
    group by c.card_id, c.language
    on conflict (tcg_account_id, card_id, language)
      do update set quantity = t.quantity + excluded.quantity, updated_at = now();
  else
    raise exception 'Unknown card category %', p_category using errcode = '22023';
  end if;

  get diagnostics saved = row_count;

  -- Each recipient sees the cards from their own point of view. Restrict the
  -- pairs to the submitted card AND language on the list that was changed.
  with added as (
    select distinct c.card_id, c.language
    from jsonb_to_recordset(p_cards) as c(card_id uuid, language text, quantity integer)
  ), pairs as (
    select distinct on (a.tcg_account_id)
      a.user_id, a.tcg_account_id, mt.card_id as my_card, pt.card_id as their_card
    from public.cards_available_for_trade pt
    join public.wishlist mw on mw.card_id = pt.card_id and mw.language = pt.language
    join public.player_tcg_account a on a.tcg_account_id = mw.tcg_account_id
    join public.card pc on pc.card_id = pt.card_id
    join public.cards_available_for_trade mt on mt.tcg_account_id = a.tcg_account_id
    join public.card mc on mc.card_id = mt.card_id and mc.rarity_id = pc.rarity_id
    join public.wishlist pw on pw.tcg_account_id = p_tcg_account_id
      and pw.card_id = mt.card_id and pw.language = mt.language
    where pt.tcg_account_id = p_tcg_account_id
      and a.user_id <> (select auth.uid())
      and public.rarity_is_tradable(pc.rarity_id)
      and not exists (select 1 from public.exclusive_trade e where e.trade_card_id = pt.id)
      and not exists (select 1 from public.exclusive_trade e where e.trade_card_id = mt.id)
      and exists (
        select 1 from added c
        where (p_category = 'trade' and c.card_id = pt.card_id and c.language = pt.language)
           or (p_category = 'wishlist' and c.card_id = pw.card_id and c.language = pw.language)
      )
    order by a.tcg_account_id, mt.card_id, pt.card_id, mt.language, pt.language
  )
  insert into public.notification
    (user_id, tcg_account_id, kind, partner_name, my_card_id, their_card_id, match_account)
  select p.user_id, p.tcg_account_id, 'trade_match',
    public.trade_account_name(p_tcg_account_id), p.my_card, p.their_card, p_tcg_account_id
  from pairs p
  where not exists (
    select 1 from public.notification n
    where n.kind = 'trade_match' and n.tcg_account_id = p.tcg_account_id
      and n.match_account = p_tcg_account_id
      and n.created_at > now() - interval '24 hours'
  );

  if p_category = 'trade' then
    -- The limit spans all of the adder's Pocket accounts, so serialize by user too.
    perform 1 from public.user_account where user_id = auth.uid() for no key update;
    with added as (
      select distinct c.card_id,c.language from jsonb_to_recordset(p_cards) as c(card_id uuid,language text,quantity integer)
    )
    insert into public.notification(user_id,tcg_account_id,kind,their_card_id,partner_name,friend_user,match_account)
    select distinct a.user_id,a.tcg_account_id,'friend_card',c.card_id,coalesce(u.username,''),u.user_id,p_tcg_account_id
    from added c join public.wishlist w on w.card_id = c.card_id and w.language = c.language
    join public.player_tcg_account a on a.tcg_account_id = w.tcg_account_id
    join public.friendship f on f.status = 'accepted' and
      ((f.requester = auth.uid() and f.addressee = a.user_id) or (f.addressee = auth.uid() and f.requester = a.user_id))
    join public.user_account u on u.user_id = auth.uid()
    where not exists(select 1 from public.notification n where n.kind = 'friend_card'
      and n.tcg_account_id = a.tcg_account_id and n.friend_user = u.user_id and n.their_card_id = c.card_id
      and n.created_at > now() - interval '24 hours');
  end if;

  return saved;
end $$;

