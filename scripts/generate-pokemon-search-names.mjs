// Generate a new data migration from PokéAPI's species names. No database access.
// Usage: node scripts/generate-pokemon-search-names.mjs supabase/migrations/<timestamp>_pokemon_search_names_data.sql
import { writeFile } from 'node:fs/promises';

const output = process.argv[2];
if (!output?.endsWith('.sql')) throw new Error('Pass a new .sql migration path.');
const source = 'https://raw.githubusercontent.com/PokeAPI/pokeapi';
const response = await fetch('https://api.github.com/repos/PokeAPI/pokeapi/commits/master');
if (!response.ok) throw new Error(`Source revision: HTTP ${response.status}`);
const { sha } = await response.json();
const csvResponse = await fetch(`${source}/${sha}/data/v2/csv/pokemon_species_names.csv`);
if (!csvResponse.ok) throw new Error(`Species names: HTTP ${csvResponse.status}`);
// Only the first three CSV fields are needed. Species names contain no commas
// or quotes; reject unexpected input rather than silently misreading it.
const rows = (await csvResponse.text()).trim().split(/\r?\n/).slice(1).map((line) => {
  const match = line.match(/^(\d+),(\d+),([^",]+),/u);
  if (!match) throw new Error(`Unexpected CSV row: ${line}`);
  return { id: match[1], language: Number(match[2]), name: match[3] };
});
const normalize = (name) => name.normalize('NFKC').replace(/[’‘]/gu, "'").toLowerCase().trim();
const english = new Map(rows.filter((row) => row.language === 9).map((row) => [row.id, normalize(row.name)]));
const aliases = new Map();
for (const row of rows) {
  const name = english.get(row.id);
  const alias = normalize(row.name);
  if (!name) throw new Error(`Missing English name for species ${row.id}`);
  if (name !== alias) aliases.set(JSON.stringify([name, alias]), [name, alias]);
}
if (english.size < 1000 || !aliases.has(JSON.stringify(['bulbasaur', 'フシギダネ']))) {
  throw new Error('Incomplete species-name data.');
}
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const values = [...aliases.values()].sort(([a, b], [c, d]) => a.localeCompare(c) || b.localeCompare(d));
const sql = `-- Generated by scripts/generate-pokemon-search-names.mjs\n-- Source: ${source}/${sha}/data/v2/csv/pokemon_species_names.csv\n-- License: docs/licenses/pokeapi.txt\n-- ${english.size} species; ${values.length} distinct translated names and romanizations.\n\nINSERT INTO public.pokemon_search_name (english_name, alias) VALUES\n${values.map((pair) => `  (${pair.map(quote).join(', ')})`).join(',\n')}\nON CONFLICT (english_name, alias) DO NOTHING;\n`;
await writeFile(output, sql, { encoding: 'utf8', flag: 'wx' });
console.log(`Generated ${output}: ${english.size} species, ${values.length} aliases (${sha}).`);
